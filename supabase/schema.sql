-- =====================================================================
-- 늘샘교회 교역자 업무분장 — Supabase 테이블 만들기
-- Supabase 대시보드 > SQL Editor > New query 에 이 파일 전체를 붙여 넣고 Run.
-- 여러 번 실행해도 안전합니다 (이미 있는 것은 건너뜀).
--
-- 접근 규칙 (요청하신 대로)
--   · 링크를 아는 사람은 누구나 읽기·추가·수정 가능
--   · 완전 삭제는 막혀 있음 → 화면의 '삭제'는 숨김(deleted = true) 처리
--   · 모든 추가·수정은 change_log 에 자동 기록 → 화면에서 되돌리기 가능
-- =====================================================================

-- ---------- 교역자 명단 ----------
create table if not exists public.staff (
  id          bigint generated by default as identity primary key,
  name        text not null unique check (char_length(name) between 1 and 40),
  short       text not null check (char_length(short) between 1 and 20), -- 협력 칸에서 찾을 짧은 이름 (예: 노주희)
  sort        int  not null default 100,
  deleted     boolean not null default false,
  updated_at  timestamptz not null default now(),
  updated_by  text check (char_length(updated_by) <= 40)
);

-- ---------- 업무분장표 ----------
create table if not exists public.tasks (
  id           bigint generated by default as identity primary key,
  no           int,
  category     text not null check (char_length(category) between 1 and 40),        -- 카테고리(부서)
  subcategory  text not null default '' check (char_length(subcategory) <= 60),     -- 중분류
  title        text not null check (char_length(title) between 1 and 300),          -- 세부 업무
  schedule     text not null default '' check (char_length(schedule) <= 120),       -- 주기·시기
  lead         text not null default '' check (char_length(lead) <= 120),           -- 주담당 (여러 명은 쉼표)
  coop         text not null default '' check (char_length(coop) <= 200),           -- 협력
  status       text not null default '미배정' check (status in ('확정', '확인필요', '미배정')),
  note         text not null default '' check (char_length(note) <= 500),           -- 비고
  kind         text not null default '정기' check (kind in ('정기', '수시', '특별절기')),
  deleted      boolean not null default false,
  updated_at   timestamptz not null default now(),
  updated_by   text check (char_length(updated_by) <= 40)
);

-- ---------- 주간 일정 ----------
create table if not exists public.weekly (
  id          bigint generated by default as identity primary key,
  person      text not null unique check (char_length(person) between 1 and 40),
  sort        int  not null default 100,
  sun text not null default '' check (char_length(sun) <= 600),
  mon text not null default '' check (char_length(mon) <= 600),
  tue text not null default '' check (char_length(tue) <= 600),
  wed text not null default '' check (char_length(wed) <= 600),
  thu text not null default '' check (char_length(thu) <= 600),
  fri text not null default '' check (char_length(fri) <= 600),
  sat text not null default '' check (char_length(sat) <= 600),
  deleted     boolean not null default false,
  updated_at  timestamptz not null default now(),
  updated_by  text check (char_length(updated_by) <= 40)
);

-- ---------- 예배별 담당 ----------
create table if not exists public.services (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 60),
  sort        int  not null default 100,
  prep        text not null default '' check (char_length(prep) <= 300),       -- 준비·세팅
  sermon      text not null default '' check (char_length(sermon) <= 300),     -- 설교
  praise      text not null default '' check (char_length(praise) <= 300),     -- 찬양인도
  slide_make  text not null default '' check (char_length(slide_make) <= 300), -- 자막 제작
  slide_run   text not null default '' check (char_length(slide_run) <= 300),  -- 자막 넘기기
  sound       text not null default '' check (char_length(sound) <= 300),      -- 음향
  broadcast   text not null default '' check (char_length(broadcast) <= 300),  -- 방송 보조
  video       text not null default '' check (char_length(video) <= 300),      -- 영상 편집
  vehicle     text not null default '' check (char_length(vehicle) <= 300),    -- 차량운행
  etc         text not null default '' check (char_length(etc) <= 300),        -- 기타
  deleted     boolean not null default false,
  updated_at  timestamptz not null default now(),
  updated_by  text check (char_length(updated_by) <= 40)
);

-- ---------- 연간 스케줄러 ----------
create table if not exists public.annual (
  id          bigint generated by default as identity primary key,
  sort        int  not null default 100,
  dept        text not null check (char_length(dept) between 1 and 40),     -- 부서
  task        text not null check (char_length(task) between 1 and 120),    -- 업무
  owner       text not null default '미정' check (char_length(owner) <= 60), -- 담당
  months      jsonb not null default '{}'::jsonb check (jsonb_typeof(months) = 'object' and pg_column_size(months) < 8000),
  deleted     boolean not null default false,
  updated_at  timestamptz not null default now(),
  updated_by  text check (char_length(updated_by) <= 40)
);

-- ---------- 교회 일정 ----------
create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  month       text not null check (month ~ '^[0-9]{4}-[0-9]{2}$'),
  label       text not null check (char_length(label) between 1 and 120),
  expected    boolean not null default false,   -- true = 예상 일정
  sort        int  not null default 100,
  deleted     boolean not null default false,
  updated_at  timestamptz not null default now(),
  updated_by  text check (char_length(updated_by) <= 40)
);

-- ---------- 변경 기록 ----------
create table if not exists public.change_log (
  id          bigint generated always as identity primary key,
  table_name  text not null,
  row_id      bigint,
  action      text not null,          -- insert / update
  before      jsonb,
  after       jsonb,
  changed_by  text,
  changed_at  timestamptz not null default now()
);
create index if not exists change_log_changed_at_idx on public.change_log (changed_at desc);

-- ---------- 트리거: 수정 시각 자동 갱신 + 변경 기록 ----------
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

create or replace function public.log_change() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.change_log (table_name, row_id, action, before, after, changed_by)
    values (tg_table_name, new.id, 'insert', null, to_jsonb(new), new.updated_by);
  elsif tg_op = 'UPDATE' then
    if (to_jsonb(old) - 'updated_at' - 'updated_by') is distinct from (to_jsonb(new) - 'updated_at' - 'updated_by') then
      insert into public.change_log (table_name, row_id, action, before, after, changed_by)
      values (tg_table_name, new.id, 'update', to_jsonb(old), to_jsonb(new), new.updated_by);
    end if;
  end if;
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['staff', 'tasks', 'weekly', 'services', 'annual', 'events'] loop
    execute format('drop trigger if exists %I on public.%I', t || '_touch', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.touch_updated_at()', t || '_touch', t);
    execute format('drop trigger if exists %I on public.%I', t || '_log', t);
    execute format('create trigger %I after insert or update on public.%I for each row execute function public.log_change()', t || '_log', t);
  end loop;
end $$;

-- ---------- 접근 규칙 (RLS) ----------
do $$
declare t text;
begin
  foreach t in array array['staff', 'tasks', 'weekly', 'services', 'annual', 'events'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "누구나 읽기" on public.%I', t);
    execute format('create policy "누구나 읽기" on public.%I for select to anon, authenticated using (true)', t);
    execute format('drop policy if exists "누구나 추가" on public.%I', t);
    execute format('create policy "누구나 추가" on public.%I for insert to anon, authenticated with check (true)', t);
    execute format('drop policy if exists "누구나 수정" on public.%I', t);
    execute format('create policy "누구나 수정" on public.%I for update to anon, authenticated using (true) with check (true)', t);
    -- 삭제 정책은 만들지 않음 → 완전 삭제 불가
    execute format('grant select, insert, update on public.%I to anon, authenticated', t);
  end loop;
end $$;

alter table public.change_log enable row level security;
drop policy if exists "누구나 읽기" on public.change_log;
create policy "누구나 읽기" on public.change_log for select to anon, authenticated using (true);
grant select on public.change_log to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ---------- 이름 바꾸기 (예: '남자 전도사' → 실제 이름) ----------
create or replace function public.rename_person(old_name text, new_name text, new_short text, editor text)
returns void language plpgsql security invoker set search_path = public as $$
declare old_short text;
begin
  if coalesce(trim(new_name), '') = '' or coalesce(trim(new_short), '') = '' then
    raise exception '새 이름과 짧은 이름을 모두 적어 주세요.';
  end if;
  select short into old_short from public.staff where name = old_name;
  if old_short is null then
    raise exception '명단에 없는 이름입니다: %', old_name;
  end if;

  update public.staff set name = new_name, short = new_short, updated_by = editor where name = old_name;

  update public.tasks
     set lead = array_to_string(array(
           select case when trim(x) = old_name then new_name else trim(x) end
             from unnest(string_to_array(lead, ',')) as x), ', '),
         updated_by = editor
   where lead like '%' || old_name || '%';

  update public.tasks set coop = replace(coop, old_name, new_name), updated_by = editor where coop like '%' || old_name || '%';
  if old_short <> old_name then
    update public.tasks set coop = replace(coop, old_short, new_short), updated_by = editor where coop like '%' || old_short || '%';
  end if;

  update public.weekly set person = new_name, updated_by = editor where person = old_name;
  update public.annual set owner = replace(owner, old_name, new_name), updated_by = editor where owner like '%' || old_name || '%';
  update public.services
     set prep = replace(prep, old_name, new_name), sermon = replace(sermon, old_name, new_name),
         praise = replace(praise, old_name, new_name), slide_make = replace(slide_make, old_name, new_name),
         slide_run = replace(slide_run, old_name, new_name), sound = replace(sound, old_name, new_name),
         broadcast = replace(broadcast, old_name, new_name), video = replace(video, old_name, new_name),
         vehicle = replace(vehicle, old_name, new_name), etc = replace(etc, old_name, new_name),
         updated_by = editor
   where concat_ws(' ', prep, sermon, praise, slide_make, slide_run, sound, broadcast, video, vehicle, etc) like '%' || old_name || '%';
end $$;
grant execute on function public.rename_person(text, text, text, text) to anon, authenticated;

-- ---------- 실시간 반영 (다른 사람이 고치면 화면이 바로 바뀜) ----------
do $$
declare t text;
begin
  foreach t in array array['staff', 'tasks', 'weekly', 'services', 'annual', 'events'] loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', t);
    exception when duplicate_object then null;
              when undefined_object then null;
    end;
  end loop;
end $$;

